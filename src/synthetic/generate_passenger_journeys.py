def validate_and_export_final_journeys(journeys, output_path):
    """
    Runs the final quality checks on the synthetic passenger journey dataset
    and exports it only when the dataset is ready for the next pipeline stage.
    """

    print("\n" + "=" * 60)
    print("FINAL SYNTHETIC DATASET VALIDATION")
    print("=" * 60)

    # These are the fields I expect every completed journey record to contain.
    required_columns = [
        "journey_id",
        "journey_date",
        "day_of_week",
        "trip_id",
        "route_id",
        "transport_mode",
        "origin_stop_id",
        "origin_stop_name",
        "origin_stop_sequence",
        "destination_stop_id",
        "destination_stop_name",
        "destination_stop_sequence",
        "scheduled_departure_time",
        "scheduled_arrival_time",
        "scheduled_duration_minutes",
        "passenger_category",
        "payment_method",
        "fare_amount",
        "validation_status",
        "compliance_status",
    ]

    # I check the schema first so the export does not silently lose
    # an important field needed later in Databricks, SQL or Power BI.
    missing_columns = [
        column
        for column in required_columns
        if column not in journeys.columns
    ]

    print(f"Total journey records: {len(journeys):,}")
    print(f"Expected core columns: {len(required_columns)}")
    print(f"Missing required columns: {len(missing_columns)}")

    if missing_columns:
        print(f"Missing columns: {missing_columns}")
        raise ValueError(
            "Final dataset is missing one or more required columns."
        )

    # Each synthetic journey needs its own identifier.
    duplicate_journey_ids = journeys["journey_id"].duplicated().sum()

    # These fields form the core of a usable passenger journey record.
    critical_columns = [
        "journey_id",
        "journey_date",
        "trip_id",
        "route_id",
        "transport_mode",
        "origin_stop_id",
        "destination_stop_id",
        "passenger_category",
        "payment_method",
        "fare_amount",
        "validation_status",
        "compliance_status",
    ]

    missing_critical_values = (
        journeys[critical_columns]
        .isna()
        .sum()
        .sum()
    )

    # The destination has to occur after the origin on the selected GTFS trip.
    invalid_stop_order = (
        journeys["destination_stop_sequence"]
        <= journeys["origin_stop_sequence"]
    ).sum()

    # A completed synthetic fare should always be greater than zero.
    invalid_fares = (
        journeys["fare_amount"] <= 0
    ).sum()

    # Journey dates should remain inside the period chosen for this dataset.
    journey_dates = pd.to_datetime(
        journeys["journey_date"],
        errors="coerce"
    )

    invalid_dates = journey_dates.isna().sum()

    if invalid_dates == 0 and len(journeys) > 0:
        earliest_date = journey_dates.min().date()
        latest_date = journey_dates.max().date()
    else:
        earliest_date = None
        latest_date = None

    print(f"Duplicate journey IDs: {duplicate_journey_ids}")
    print(f"Missing critical values: {missing_critical_values}")
    print(f"Invalid origin-destination order: {invalid_stop_order}")
    print(f"Invalid fares: {invalid_fares}")
    print(f"Invalid journey dates: {invalid_dates}")
    print(f"Earliest journey date: {earliest_date}")
    print(f"Latest journey date: {latest_date}")

    validation_failures = {
        "duplicate journey IDs": duplicate_journey_ids,
        "missing critical values": missing_critical_values,
        "invalid origin-destination order": invalid_stop_order,
        "invalid fares": invalid_fares,
        "invalid journey dates": invalid_dates,
    }

    failed_checks = {
        name: value
        for name, value in validation_failures.items()
        if value > 0
    }

    if failed_checks:
        print("\nFinal synthetic dataset validation status: FAIL")
        print(f"Failed checks: {failed_checks}")

        raise ValueError(
            "Synthetic passenger journey dataset failed final validation."
        )

    print("\nFinal synthetic dataset validation status: PASS")

    # I keep the exported table in a predictable column order so later
    # pipeline stages receive the same schema every time this script runs.
    remaining_columns = [
        column
        for column in journeys.columns
        if column not in required_columns
    ]

    export_columns = required_columns + remaining_columns
    final_journeys = journeys[export_columns].copy()

    # The synthetic folder already separates generated passenger records
    # from the real GTFS reference data used to construct the journeys.
    output_path.parent.mkdir(parents=True, exist_ok=True)

    final_journeys.to_csv(
        output_path,
        index=False
    )

    print("\n" + "=" * 60)
    print("SYNTHETIC PASSENGER JOURNEY EXPORT")
    print("=" * 60)

    print(f"Output file: {output_path}")
    print(f"Rows exported: {len(final_journeys):,}")
    print(f"Columns exported: {len(final_journeys.columns)}")
    print(f"File size: {output_path.stat().st_size / (1024 ** 2):.2f} MB")

    print("\nSynthetic passenger journey dataset export: COMPLETE")

    return final_journeys


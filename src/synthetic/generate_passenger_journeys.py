PROJECT_ROOT = Path(__file__).resolve().parents[2]

DUBLIN_DATA_DIR = PROJECT_ROOT / "data" / "processed" / "dublin"
SYNTHETIC_DATA_DIR = PROJECT_ROOT / "data" / "synthetic"

SYNTHETIC_DATA_DIR.mkdir(parents=True, exist_ok=True)

# SYNTHETIC GENERATION CONFIGURATION

RANDOM_SEED = 42
INITIAL_JOURNEY_COUNT = 1_000

SYNTHETIC_START_DATE = date(2026, 9, 30)
SYNTHETIC_END_DATE = date(2026, 10, 30)

# INPUT FILES

ROUTES_FILE = DUBLIN_DATA_DIR / "routes.csv"
TRIPS_FILE = DUBLIN_DATA_DIR / "trips.csv"
STOPS_FILE = DUBLIN_DATA_DIR / "stops.csv"
STOP_TIMES_FILE = DUBLIN_DATA_DIR / "stop_times.csv"
CALENDAR_FILE = DUBLIN_DATA_DIR / "calendar.csv"
CALENDAR_DATES_FILE = DUBLIN_DATA_DIR / "calendar_dates.csv"


# DATA LOADING

def load_dublin_network():
    """
    Load the processed Dublin GTFS analytical network.

    Returns
    -------
    tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]
        routes, trips, stops and stop_times.
    """

    print("=" * 60)
    print("LOADING CORE DUBLIN TRANSPORT NETWORK")
    print("=" * 60)

    required_files = [ROUTES_FILE, TRIPS_FILE, STOPS_FILE, STOP_TIMES_FILE,]

    missing_files = [
        file_path
        for file_path in required_files
        if not file_path.exists()
    ]

    if missing_files:
        missing_names = ", ".join(
            file_path.name for file_path in missing_files
        )

        raise FileNotFoundError(
            f"Missing required Dublin network files: {missing_names}"
        )

    routes = pd.read_csv(ROUTES_FILE, dtype=str,)

    trips = pd.read_csv(TRIPS_FILE, dtype=str,)

    stops = pd.read_csv(STOPS_FILE,dtype=str,)

    stop_times = pd.read_csv(STOP_TIMES_FILE, dtype=str,)

    print(f"Routes loaded: {len(routes):,}")
    print(f"Trips loaded: {len(trips):,}")
    print(f"Stops loaded: {len(stops):,}")
    print(f"Stop-time records loaded: {len(stop_times):,}")

    return routes, trips, stops, stop_times



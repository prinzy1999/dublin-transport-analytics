def enrich_transport_mode(
    journeys,
    routes,
):
    """
    Add a readable transport mode to each synthetic journey.

    The mode is derived from the GTFS route_type attached to the
    real route used by the synthetic journey.
    """

    print("\n" + "=" * 60)
    print("ENRICHING JOURNEYS WITH TRANSPORT MODE")
    print("=" * 60)

    required_route_columns = {
        "route_id",
        "route_type",
    }

    missing_columns = (
        required_route_columns
        - set(routes.columns)
    )

    if missing_columns:
        raise ValueError(
            "Routes data is missing fields needed to derive "
            f"transport mode: {sorted(missing_columns)}"
        )

    route_reference = routes[
        [
            "route_id",
            "route_type",
        ]
    ].copy()

    route_reference = route_reference.drop_duplicates(
        subset=["route_id"]
    )

    # GTFS stores the transport type as a numeric code. I keep the
    # original route_type and add a readable version for analysis.
    route_type_to_mode = {
        "0": "Luas",
        "1": "Metro",
        "2": "Rail",
        "3": "Bus",
        "4": "Ferry",
        "5": "Cable Tram",
        "6": "Aerial Lift",
        "7": "Funicular",
        "11": "Trolleybus",
        "12": "Monorail",
    }

    route_reference["transport_mode"] = (
        route_reference["route_type"]
        .astype(str)
        .str.strip()
        .map(route_type_to_mode)
        .fillna("Other")
    )

    enriched = journeys.merge(
        route_reference[
            [
                "route_id",
                "route_type",
                "transport_mode",
            ]
        ],
        on="route_id",
        how="left",
        validate="many_to_one",
    )

    missing_modes = (
        enriched["transport_mode"]
        .isna()
        .sum()
    )

    print(
        "Journeys with missing transport mode: "
        f"{missing_modes:,}"
    )

    print("\nJourneys by transport mode:")
    print(
        enriched["transport_mode"]
        .value_counts(
            dropna=False
        )
        .to_string()
    )

    print("\nGTFS route types represented:")
    print(
        enriched["route_type"]
        .value_counts(
            dropna=False
        )
        .sort_index()
        .to_string()
    )

    return enriched



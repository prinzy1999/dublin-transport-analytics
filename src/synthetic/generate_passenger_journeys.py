def add_fare_compliance_attributes(
    journeys,
    random_seed=RANDOM_SEED,
):
    """
    Add simulated fare-validation and compliance information.

    These values are synthetic. They are included so the project can
    analyse fare behaviour without using real passenger or inspection data.
    """

    print("\n" + "=" * 60)
    print("GENERATING SYNTHETIC FARE AND COMPLIANCE DATA")
    print("=" * 60)

    enriched = journeys.copy()

    # I keep this random generator separate from the earlier layers so
    # rerunning the project produces the same fare-compliance dataset.
    rng = random.Random(
        random_seed + 3
    )

    fare_amounts = []
    validation_statuses = []
    compliance_statuses = []

    for journey in enriched.itertuples(index=False):

        transport_mode = journey.transport_mode
        passenger_category = journey.passenger_category
        payment_method = journey.payment_method

        # These are simulated analytical fares rather than published
        # transport fares. Their purpose is to give the later SQL and BI
        # layers a sensible numeric measure to work with.
        base_fare_ranges = {
            "Bus": (2.00, 4.00),
            "Luas": (2.00, 4.00),
            "Rail": (2.50, 6.50),
        }

        minimum_fare, maximum_fare = base_fare_ranges.get(
            transport_mode,
            (2.00, 5.00),
        )

        fare_amount = rng.uniform(
            minimum_fare,
            maximum_fare,
        )

        # Synthetic passenger categories receive different analytical
        # adjustments so the generated dataset is not completely uniform.
        passenger_adjustments = {
            "Adult": 1.00,
            "Student": 0.75,
            "Young Adult": 0.75,
            "Child": 0.50,
            "Senior": 0.50,
        }

        adjustment = passenger_adjustments.get(
            passenger_category,
            1.00,
        )

        fare_amount = round(
            fare_amount * adjustment,
            2,
        )

        fare_amounts.append(
            fare_amount
        )

        # Most synthetic journeys are intentionally valid, while a smaller
        # number contain validation problems for the compliance analysis.
        validation_status = rng.choices(
            population=[
                "Validated",
                "Not Validated",
                "Validation Error",
            ],
            weights=[
                91,
                6,
                3,
            ],
            k=1,
        )[0]

        validation_statuses.append(
            validation_status
        )

        # Compliance is derived from the simulated validation result rather
        # than generated independently, which keeps the fields consistent.
        if validation_status == "Validated":
            compliance_status = "Compliant"

        elif validation_status == "Not Validated":
            compliance_status = "Non-Compliant"

        else:
            compliance_status = "Validation Issue"

        compliance_statuses.append(
            compliance_status
        )

    enriched["fare_amount"] = fare_amounts

    enriched["validation_status"] = (
        validation_statuses
    )

    enriched["compliance_status"] = (
        compliance_statuses
    )

    print(
        f"Fare/compliance records generated: "
        f"{len(enriched):,}"
    )

    print("\nValidation outcomes:")
    print(
        enriched["validation_status"]
        .value_counts()
        .to_string()
    )

    print("\nCompliance outcomes:")
    print(
        enriched["compliance_status"]
        .value_counts()
        .to_string()
    )

    print("\nAverage synthetic fare by transport mode:")
    print(
        enriched.groupby(
            "transport_mode"
        )["fare_amount"]
        .mean()
        .round(2)
        .to_string()
    )

    return enriched



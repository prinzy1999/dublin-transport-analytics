# VALID JOURNEY CONSTRUCTION

def prepare_stop_times(stop_times):
    """
    Prepare GTFS stop-time records for journey construction.

    The stop_sequence field determines the order in which a
    vehicle visits stops during a trip.
    """

    print("\n" + "=" * 60)
    print("PREPARING STOP-TIME DATA")
    print("=" * 60)

    prepared = stop_times.copy()

    # Converting stop_sequence from string to numeric so that stops
    # can be sorted correctly within each trip.
    prepared["stop_sequence"] = pd.to_numeric(
        prepared["stop_sequence"],
        errors="coerce",
    )

    invalid_sequence_count = (
        prepared["stop_sequence"].isna().sum()
    )

    if invalid_sequence_count > 0:
        print(
            "Removing stop-time records with invalid "
            f"stop_sequence: {invalid_sequence_count:,}"
        )

        prepared = prepared.dropna(
            subset=["stop_sequence"]
        )

    # Removing records missing the identifiers required to
    # construct a journey.
    missing_identifiers = (
        prepared["trip_id"].isna()
        | prepared["stop_id"].isna()
    )

    missing_identifier_count = (
        missing_identifiers.sum()
    )

    if missing_identifier_count > 0:
        print(
            "Removing stop-time records with missing "
            f"trip/stop identifiers: {missing_identifier_count:,}"
        )

        prepared = prepared.loc[
            ~missing_identifiers
        ].copy()

    # Sort the records into their actual stop order.
    prepared = prepared.sort_values(
        by=[
            "trip_id",
            "stop_sequence",
        ]
    ).reset_index(drop=True)

    print(
        f"Prepared stop-time records: "
        f"{len(prepared):,}"
    )

    return prepared


def identify_usable_trips(trips, stop_times):
    """
    Identify GTFS trips that can support a passenger journey.

    A usable trip must contain at least two distinct stops so
    that an origin and a later destination can be selected.
    """

    print("\n" + "=" * 60)
    print("IDENTIFYING USABLE TRIPS")
    print("=" * 60)

    trip_stop_summary = (
        stop_times
        .groupby("trip_id")
        .agg(
            stop_event_count=(
                "stop_id",
                "size",
            ),
            distinct_stop_count=(
                "stop_id",
                "nunique",
            ),
        )
        .reset_index()
    )

    usable_trip_ids = trip_stop_summary.loc[
        (
            trip_stop_summary[
                "stop_event_count"
            ] >= 2
        )
        & (
            trip_stop_summary[
                "distinct_stop_count"
            ] >= 2
        ),
        "trip_id",
    ]

    usable_trips = trips[
        trips["trip_id"].isin(
            usable_trip_ids
        )
    ].copy()

    print(
        f"Total GTFS trips: "
        f"{len(trips):,}"
    )

    print(
        f"Trips with valid origin-destination structure: "
        f"{len(usable_trips):,}"
    )

    removed_trips = (
        len(trips)
        - len(usable_trips)
    )

    print(
        f"Trips excluded: "
        f"{removed_trips:,}"
    )

    return usable_trips


def build_trip_stop_lookup(
    usable_trips,
    stop_times,
    stops,
):
    """
    Build a lookup containing the ordered stops for each
    usable GTFS trip.

    The resulting dictionary allows the synthetic journey
    generator to select an origin stop and a destination stop
    that actually occur on the same trip and in the correct
    order.
    """

    print("\n" + "=" * 60)
    print("BUILDING TRIP-STOP LOOKUP")
    print("=" * 60)

    usable_trip_ids = set(
        usable_trips["trip_id"]
    )

    relevant_stop_times = stop_times[
        stop_times["trip_id"].isin(
            usable_trip_ids
        )
    ].copy()

    # Attach stop names so future synthetic journey records
    # can contain both IDs and readable stop descriptions.
    stop_reference = (
        stops[
            [
                "stop_id",
                "stop_name",
            ]
        ]
        .drop_duplicates(
            subset=["stop_id"]
        )
    )

    relevant_stop_times = (
        relevant_stop_times.merge(
            stop_reference,
            on="stop_id",
            how="left",
            validate="many_to_one",
        )
    )

    relevant_stop_times = (
        relevant_stop_times.sort_values(
            by=[
                "trip_id",
                "stop_sequence",
            ]
        )
    )

    trip_stop_lookup = {}

    for trip_id, group in (
        relevant_stop_times.groupby(
            "trip_id",
            sort=False,
        )
    ):

        ordered_stops = (
            group[
                [
                    "stop_id",
                    "stop_name",
                    "stop_sequence",
                ]
            ]
            .sort_values(
                "stop_sequence"
            )
            .to_dict(
                orient="records"
            )
        )

        if len(ordered_stops) >= 2:
            trip_stop_lookup[
                trip_id
            ] = ordered_stops

    print(
        f"Trips added to stop lookup: "
        f"{len(trip_stop_lookup):,}"
    )

    return trip_stop_lookup


def validate_trip_stop_lookup(
    trip_stop_lookup,
):
    """
    Validate that every trip in the lookup can produce a
    correctly ordered origin-to-destination journey.
    """

    print("\n" + "=" * 60)
    print("VALIDATING TRIP-STOP LOOKUP")
    print("=" * 60)

    if not trip_stop_lookup:
        raise ValueError(
            "Trip-stop lookup is empty."
        )

    invalid_trips = []

    for trip_id, ordered_stops in (
        trip_stop_lookup.items()
    ):

        if len(ordered_stops) < 2:
            invalid_trips.append(
                trip_id)
            continue

        sequences = [stop["stop_sequence"]
            for stop in ordered_stops]

        if sequences != sorted(sequences):
            invalid_trips.append(trip_id)

    if invalid_trips:
        sample_invalid = (invalid_trips[:10])

        raise ValueError("Trip-stop lookup contains invalid trips. "
            f"Example trip IDs: {sample_invalid}")

    print(
        f"Validated trips: "
        f"{len(trip_stop_lookup):,}"
    )

    print("Trip-stop lookup status: PASS")

# GTFS SERVICE CALENDAR VALIDATION

def build_valid_service_dates(start_date=SYNTHETIC_START_DATE,
                              end_date=SYNTHETIC_END_DATE):
    """Expand GTFS weekly services and date exceptions into valid service dates."""
    if end_date < start_date:
        raise ValueError("Synthetic end date cannot precede start date.")
    if not CALENDAR_FILE.exists() and not CALENDAR_DATES_FILE.exists():
        raise FileNotFoundError(
            "Expected calendar.csv and/or calendar_dates.csv in "
            f"{DUBLIN_DATA_DIR}. Process the matching GTFS feed first."
        )

    valid = {}
    weekdays = ["monday", "tuesday", "wednesday", "thursday",
                "friday", "saturday", "sunday"]
    if CALENDAR_FILE.exists():
        calendar = pd.read_csv(CALENDAR_FILE, dtype=str).fillna("")
        required = {"service_id", "start_date", "end_date", *weekdays}
        if not required.issubset(calendar.columns):
            raise ValueError(f"calendar.csv missing: {sorted(required - set(calendar.columns))}")
        for row in calendar.to_dict("records"):
            first = pd.to_datetime(row["start_date"], format="%Y%m%d", errors="coerce")
            last = pd.to_datetime(row["end_date"], format="%Y%m%d", errors="coerce")
            if pd.isna(first) or pd.isna(last):
                raise ValueError(f"Invalid calendar dates for service {row['service_id']}")
            current = max(start_date, first.date())
            finish = min(end_date, last.date())
            while current <= finish:
                if row[weekdays[current.weekday()]].strip() == "1":
                    valid.setdefault(row["service_id"], set()).add(current)
                current += timedelta(days=1)

    if CALENDAR_DATES_FILE.exists():
        exceptions = pd.read_csv(CALENDAR_DATES_FILE, dtype=str).fillna("")
        required = {"service_id", "date", "exception_type"}
        if not required.issubset(exceptions.columns):
            raise ValueError(f"calendar_dates.csv missing: {sorted(required - set(exceptions.columns))}")
        for row in exceptions.to_dict("records"):
            parsed = pd.to_datetime(row["date"], format="%Y%m%d", errors="coerce")
            if pd.isna(parsed):
                raise ValueError(f"Invalid exception date for service {row['service_id']}")
            day = parsed.date()
            if not start_date <= day <= end_date:
                continue
            service_days = valid.setdefault(row["service_id"], set())
            if row["exception_type"] == "1":
                service_days.add(day)
            elif row["exception_type"] == "2":
                service_days.discard(day)
            else:
                raise ValueError(f"Unknown GTFS exception_type: {row['exception_type']}")

    valid = {service: sorted(days) for service, days in valid.items() if days}
    print(f"GTFS services operating in date window: {len(valid):,}")
    if not valid:
        raise ValueError("No GTFS services operate in the requested date window.")
    return valid


# SYNTHETIC ORIGIN-DESTINATION GENERATION

def generate_origin_destination_journeys(usable_trips, trip_stop_lookup,
    journey_count, valid_service_dates, random_seed=RANDOM_SEED,):
    """
    Generate synthetic passenger journeys using valid GTFS trips.

    Each generated journey:
    - references a real GTFS trip;
    - uses an origin and destination from that trip;
    - guarantees that the destination occurs after the origin.

    No real passenger behaviour is represented.
    """

    print("\n" + "=" * 60)
    print("GENERATING SYNTHETIC ORIGIN-DESTINATION JOURNEYS")
    print("=" * 60)

    rng = random.Random(random_seed)

    trip_reference = (usable_trips[
            [
                "trip_id",
                "route_id",
                "service_id",
            ]
        ]
        .drop_duplicates(
            subset=["trip_id"]
        )
        .set_index("trip_id")
    )

    if "service_id" not in usable_trips.columns:
        raise ValueError("trips.csv must contain service_id for calendar validation.")
    available_trip_ids = [
        trip_id for trip_id in trip_stop_lookup
        if trip_id in trip_reference.index
        and trip_reference.at[trip_id, "service_id"] in valid_service_dates
    ]

    if not available_trip_ids:
        raise ValueError("No usable trips are available for synthetic generation.")

    journeys = []

    for journey_number in range(1,journey_count + 1,):

        trip_id = rng.choice(
            available_trip_ids
        )

        ordered_stops = (
            trip_stop_lookup[trip_id]
        )

        # The origin cannot be the final stop because a
        # destination must occur after it.
        origin_index = rng.randrange(
            0,
            len(ordered_stops) - 1,
        )

        destination_index = rng.randrange(
            origin_index + 1,
            len(ordered_stops),
        )

        origin = ordered_stops[
            origin_index
        ]

        destination = ordered_stops[
            destination_index
        ]

        route_id = trip_reference.loc[
            trip_id,
            "route_id",
        ]

        service_id = trip_reference.at[trip_id, "service_id"]
        journey_date = rng.choice(valid_service_dates[service_id])

        journey = {
            "journey_date": journey_date,
            "journey_id": (
                f"JNY{journey_number:07d}"
            ),
            "trip_id": trip_id,
            "route_id": route_id,

            "origin_stop_id": (
                origin["stop_id"]
            ),
            "origin_stop_name": (
                origin["stop_name"]
            ),
            "origin_stop_sequence": (
                int(
                    origin[
                        "stop_sequence"
                    ]
                )
            ),

            "destination_stop_id": (
                destination["stop_id"]
            ),
            "destination_stop_name": (
                destination["stop_name"]
            ),
            "destination_stop_sequence": (
                int(
                    destination[
                        "stop_sequence"
                    ]
                )
            ),
        }

        journeys.append(
            journey
        )

    journeys_df = pd.DataFrame(
        journeys
    )

    print(
        f"Synthetic journeys generated: "
        f"{len(journeys_df):,}"
    )

    print(
        f"Unique GTFS trips represented: "
        f"{journeys_df['trip_id'].nunique():,}"
    )

    print(
        f"Unique routes represented: "
        f"{journeys_df['route_id'].nunique():,}"
    )

    return journeys_df

def validate_synthetic_journeys(
    journeys,
):
    """
    Validate structural rules for generated synthetic journeys.
    """

    print("\n" + "=" * 60)
    print("VALIDATING SYNTHETIC JOURNEYS")
    print("=" * 60)

    required_columns = [
        "journey_id",
        "trip_id",
        "route_id",
        "origin_stop_id",
        "origin_stop_sequence",
        "destination_stop_id",
        "destination_stop_sequence",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in journeys.columns
    ]

    if missing_columns:
        raise ValueError(
            "Synthetic journey dataset is missing columns: "
            f"{missing_columns}"
        )

    duplicate_journey_ids = (
        journeys["journey_id"]
        .duplicated()
        .sum()
    )

    invalid_stop_order = (
        journeys[
            "destination_stop_sequence"
        ]
        <= journeys[
            "origin_stop_sequence"
        ]
    ).sum()

    missing_trip_ids = (
        journeys["trip_id"]
        .isna()
        .sum()
    )

    missing_route_ids = (
        journeys["route_id"]
        .isna()
        .sum()
    )

    print(
        f"Duplicate journey IDs: "
        f"{duplicate_journey_ids:,}"
    )

    print(
        f"Invalid origin-destination order: "
        f"{invalid_stop_order:,}"
    )

    print(
        f"Missing trip IDs: "
        f"{missing_trip_ids:,}"
    )

    print(
        f"Missing route IDs: "
        f"{missing_route_ids:,}"
    )

    if (
        duplicate_journey_ids > 0
        or invalid_stop_order > 0
        or missing_trip_ids > 0
        or missing_route_ids > 0
    ):
        raise ValueError(
            "Synthetic journey validation failed."
        )

    print(
        "Synthetic journey validation status: PASS"
    )


def assign_synthetic_journey_dates(journeys,
                                   start_date=SYNTHETIC_START_DATE,
                                   end_date=SYNTHETIC_END_DATE,
                                   random_seed=RANDOM_SEED):
    """Derive calendar fields from GTFS-valid dates selected during generation."""
    enriched = journeys.copy()
    if "journey_date" not in enriched.columns:
        raise ValueError("Journey dates must be assigned from GTFS service dates.")
    enriched["journey_date"] = pd.to_datetime(enriched["journey_date"])
    if not enriched["journey_date"].between(pd.Timestamp(start_date), pd.Timestamp(end_date)).all():
        raise ValueError("Generated journey date is outside the requested window.")
    enriched["day_of_week"] = enriched["journey_date"].dt.day_name()
    enriched["is_weekend"] = enriched["journey_date"].dt.dayofweek >= 5
    print(f"GTFS-valid journey dates assigned: {len(enriched):,}")
    print(f"Date range: {enriched['journey_date'].min().date()} "
          f"to {enriched['journey_date'].max().date()}")
    return enriched


def build_stop_time_schedule_lookup(
    stop_times,
):
    """
    Build a lookup containing scheduled GTFS arrival and
    departure times for each trip-stop combination.
    """

    print("\n" + "=" * 60)
    print("BUILDING STOP-TIME SCHEDULE LOOKUP")
    print("=" * 60)

    required_columns = {
        "trip_id",
        "stop_id",
        "stop_sequence",
    }

    missing_columns = (
        required_columns
        - set(stop_times.columns)
    )

    if missing_columns:
        raise ValueError(
            "stop_times is missing required schedule fields: "
            f"{sorted(missing_columns)}"
        )

    schedule_columns = [
        "trip_id",
        "stop_id",
        "stop_sequence",
    ]

    if "arrival_time" in stop_times.columns:
        schedule_columns.append(
            "arrival_time"
        )

    if "departure_time" in stop_times.columns:
        schedule_columns.append(
            "departure_time"
        )

    if (
        "arrival_time" not in schedule_columns
        and "departure_time" not in schedule_columns
    ):
        raise ValueError(
            "stop_times does not contain arrival_time "
            "or departure_time."
        )

    schedule = stop_times[
        schedule_columns
    ].copy()

    schedule["stop_sequence"] = pd.to_numeric(
        schedule["stop_sequence"],
        errors="coerce",
    )

    schedule = schedule.dropna(
        subset=[
            "trip_id",
            "stop_id",
            "stop_sequence",
        ]
    )

    schedule["stop_sequence"] = (
        schedule["stop_sequence"]
        .astype(int)
    )

    schedule = schedule.drop_duplicates(
        subset=[
            "trip_id",
            "stop_id",
            "stop_sequence",
        ]
    )

    schedule_lookup = {
        (
            row.trip_id,
            row.stop_id,
            row.stop_sequence,
        ): row
        for row in schedule.itertuples(
            index=False
        )
    }

    print(
        f"Scheduled trip-stop records available: "
        f"{len(schedule_lookup):,}"
    )

    return schedule_lookup


def attach_scheduled_times(
    journeys,
    stop_times,
):
    """
    Attach scheduled GTFS departure and arrival times to
    synthetic passenger journeys.

    The passenger record is synthetic, while the schedule
    values come from the corresponding processed GTFS trip.
    """

    print("\n" + "=" * 60)
    print("ATTACHING GTFS SCHEDULE TIMES")
    print("=" * 60)

    enriched = journeys.copy()

    schedule_lookup = (
        build_stop_time_schedule_lookup(
            stop_times
        )
    )

    scheduled_departures = []
    scheduled_arrivals = []

    for journey in enriched.itertuples(
        index=False
    ):

        origin_key = (
            journey.trip_id,
            journey.origin_stop_id,
            int(
                journey.origin_stop_sequence
            ),
        )

        destination_key = (
            journey.trip_id,
            journey.destination_stop_id,
            int(
                journey.destination_stop_sequence
            ),
        )

        origin_schedule = (
            schedule_lookup.get(
                origin_key
            )
        )

        destination_schedule = (
            schedule_lookup.get(
                destination_key
            )
        )

        if origin_schedule is None:
            scheduled_departures.append(
                None
            )
        else:
            departure_time = getattr(
                origin_schedule,
                "departure_time",
                None,
            )

            if pd.isna(departure_time):
                departure_time = getattr(
                    origin_schedule,
                    "arrival_time",
                    None,
                )

            scheduled_departures.append(
                departure_time
            )

        if destination_schedule is None:
            scheduled_arrivals.append(
                None
            )
        else:
            arrival_time = getattr(
                destination_schedule,
                "arrival_time",
                None,
            )

            if pd.isna(arrival_time):
                arrival_time = getattr(
                    destination_schedule,
                    "departure_time",
                    None,
                )

            scheduled_arrivals.append(
                arrival_time
            )

    enriched[
        "scheduled_departure_time"
    ] = scheduled_departures

    enriched[
        "scheduled_arrival_time"
    ] = scheduled_arrivals

    print(
        "Scheduled departure times attached: "
        f"{enriched['scheduled_departure_time'].notna().sum():,}"
    )

    print(
        "Scheduled arrival times attached: "
        f"{enriched['scheduled_arrival_time'].notna().sum():,}"
    )

    return enriched


def gtfs_time_to_seconds(
    time_value,
):
    """
    Convert a GTFS HH:MM:SS value to seconds.

    GTFS permits hours greater than 23 for services operating
    after midnight, so standard datetime time parsing is not used.
    """

    if pd.isna(time_value):
        return None

    try:
        hours, minutes, seconds = (
            str(time_value)
            .strip()
            .split(":")
        )

        return (
            int(hours) * 3600
            + int(minutes) * 60
            + int(seconds)
        )

    except (ValueError, AttributeError):
        return None


def calculate_scheduled_journey_duration(
    journeys,
):
    """
    Calculate scheduled journey duration from GTFS schedule times.
    """

    print("\n" + "=" * 60)
    print("CALCULATING SCHEDULED JOURNEY DURATIONS")
    print("=" * 60)

    enriched = journeys.copy()

    departure_seconds = (
        enriched[
            "scheduled_departure_time"
        ]
        .apply(
            gtfs_time_to_seconds
        )
    )

    arrival_seconds = (
        enriched[
            "scheduled_arrival_time"
        ]
        .apply(
            gtfs_time_to_seconds
        )
    )

    duration_seconds = (
        arrival_seconds
        - departure_seconds
    )

    enriched[
        "scheduled_duration_minutes"
    ] = (
        duration_seconds / 60
    )

    invalid_duration = (
        enriched[
            "scheduled_duration_minutes"
        ].isna()
        | (
            enriched[
                "scheduled_duration_minutes"
            ] < 0
        )
    )

    invalid_count = (
        invalid_duration.sum()
    )

    if invalid_count > 0:
        enriched.loc[
            invalid_duration,
            "scheduled_duration_minutes",
        ] = pd.NA

    valid_duration_count = (
        enriched[
            "scheduled_duration_minutes"
        ]
        .notna()
        .sum()
    )

    print(
        f"Valid scheduled durations: "
        f"{valid_duration_count:,}"
    )

    print(
        f"Journeys without valid duration: "
        f"{invalid_count:,}"
    )

    return enriched



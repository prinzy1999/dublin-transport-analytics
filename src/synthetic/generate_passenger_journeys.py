"""
Generate synthetic passenger journey records for the
Dublin Public Transport Fare Compliance & Passenger Journey Analytics project.

The transport network is based on processed NTA GTFS data.

Passenger journeys, ticket information, validation outcomes,
fare-compliance outcomes, and related passenger-level observations
generated by this script are entirely synthetic.

No real passenger records or confidential Tracsis survey data are used.
"""

